public class Mathfunction {
    public static void main(String[] args) {

        System.out.println(Math.PI);
        System.out.println(Math.sin(0));
        System.out.println(Math.cos(0));
        System.out.println(Math.tan(0));
        System.out.println(Math.ceil(10.5));
        System.out.println(Math.ceil(-10.5));
        System.out.println(Math.floor(10.8));
        System.out.println(Math.floor(-10.5));
        System.out.println(Math.round(10.3));
        System.out.println(Math.round(10.8));
        System.out.println(Math.sqrt(10));
        System.out.println(Math.abs(-100));
        System.out.println(Math.max(10, 20));
        System.out.println(Math.min(10, 20));
        System.out.println(Math.exp(0));
        System.out.println(Math.floorDivExact(13, 5));

        
}
}
